"""Build the offline vocabulary from the unmodified official NGSL 1.2 files.

Usage: python tools/build_ngsl.py [--inspect]
No network or third-party Python dependencies are needed.
Derived vocabulary data: CC BY-SA 4.0, see data/ngsl/NOTICE.md.
"""
import csv
import hashlib
import json
from pathlib import Path
import re
import sys
import xml.etree.ElementTree as ET
import zipfile

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'data/ngsl'


def csv_rows(name, encoding='utf-8-sig'):
    with (DATA / 'raw' / name).open(encoding=encoding, newline='') as f:
        return list(csv.DictReader(f))


def definitions():
    ns = {'s': 'http://schemas.openxmlformats.org/spreadsheetml/2006/main'}
    with zipfile.ZipFile(DATA / 'raw/ngsl_definitions.xlsx') as z:
        strings = [''.join(t.text or '' for t in e.findall('.//s:t', ns))
                   for e in ET.fromstring(z.read('xl/sharedStrings.xml'))]
        sheet = ET.fromstring(z.read('xl/worksheets/sheet1.xml'))
        rows = []
        for row in sheet.findall('s:sheetData/s:row', ns):
            cells = {}
            for cell in row:
                value = cell.find('s:v', ns)
                if value is not None:
                    cells[re.sub(r'\d', '', cell.attrib['r'])] = (
                        strings[int(value.text)] if cell.get('t') == 's' else value.text)
            rows.append(cells)
    result = {r['A'].strip().lower(): r['B'].strip() for r in rows[1:]}
    # The publisher's spoken definitions are Windows-1252, not UTF-8.
    for r in csv_rows('spoken_definitions.csv', 'cp1252'):
        values = list(r.values())
        result.setdefault(values[0].strip().lower(), values[1].strip())
    result['email'] = result.pop('e-mail')
    return result


def source_words():
    general = csv_rows('ngsl_stats.csv')
    spoken = csv_rows('spoken_stats.csv')
    assert len(general) == 2809 and len(spoken) == 721
    result = {}
    for rows, rank_key, field in [(general, 'SFI Rank', 'ngslRank'),
                                  (spoken, 'Rank', 'spokenRank')]:
        ranks = [int(r[rank_key]) for r in rows if r[rank_key].isdigit()]
        assert len(set(ranks)) == len(ranks)
        for r in rows:
            key = r['Lemma'].strip().lower()
            item = result.setdefault(key, {'headword': r['Lemma'].strip()})
            assert field not in item, f'Duplicate {field}: {key}'
            item[field] = int(r[rank_key]) if r[rank_key].isdigit() else None
            if field == 'spokenRank':
                item['spokenCore'] = True
    assert len(result) == 2833
    return result


def main():
    words = source_words()
    defs = definitions()
    assert not (set(words) - set(defs)), f'Missing English definitions: {set(words)-set(defs)}'
    if '--inspect' in sys.argv:
        print(json.dumps({'words': len(words), 'definitions': len(defs),
                          'examples': list(defs.items())[:5]}, ensure_ascii=False))
        return
    korean = {}
    for file in sorted(DATA.glob('korean_*.txt')):
        for line in file.read_text(encoding='utf-8').splitlines():
            if not line or line.startswith('#'):
                continue
            key, meaning = line.split('|', 1)
            assert key not in korean, f'Duplicate Korean entry: {key}'
            assert re.search('[가-힣]', meaning), key
            korean[key] = meaning
    missing = set(words) - set(korean)
    assert not missing, f'Missing Korean meanings ({len(missing)}): {sorted(missing)}'
    assert not set(korean) - set(words), f'Unknown entries: {set(korean)-set(words)}'
    # Spoken core first, followed by the other NGSL words in official rank order.
    ordered = sorted(words, key=lambda w: (
        0 if 'spokenRank' in words[w] else 1,
        (words[w].get('spokenRank') or 722) if 'spokenRank' in words[w]
        else words[w]['ngslRank']))
    records = []
    for index, key in enumerate(ordered):
        item = dict(words[key])
        item.update(id=key, korean=korean[key], definition=defs[key],
                    level=1 + index * 50 // len(ordered), studyOrder=index + 1)
        records.append(item)
    payload = {'license': 'CC-BY-SA-4.0',
               'attribution': 'NGSL: Browne, Culligan & Phillips; NGSL-Spoken: Browne & Culligan',
               'source': 'https://www.newgeneralservicelist.com/',
               'changes': 'Merged by lemma; added Korean glosses and app study bands. Original ranks retained.',
               'words': records}
    (ROOT / 'assets/data/ngsl.json').write_text(
        json.dumps(payload, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    def dart(value):
        return json.dumps(value, ensure_ascii=False).replace('$', r'\$')
    lines = ['// Generated by tools/build_ngsl.py. Do not edit.',
             '// Vocabulary data: CC BY-SA 4.0. See data/ngsl/NOTICE.md.',
             "import 'package:edu_voca/domain/models/word_item.dart';", '', 'const ngslVocabulary = <WordItem>[']
    for r in records:
        args = ', '.join([dart(r['id']), str(r['level']), dart(r['korean']),
                          dart(r['definition'])])
        lines.append('  WordItem.vocabulary(' + args +
                     f", ngslRank: {r.get('ngslRank') or 'null'}, spokenRank: {r.get('spokenRank') or 'null'}, spokenCore: {str(r.get('spokenCore', False)).lower()}, studyOrder: {r['studyOrder']}),")
    lines.append('];\n')
    (ROOT / 'lib/data/local/ngsl_data.dart').write_text('\n'.join(lines), encoding='utf-8')
    manifest = {'retrieved': '2026-10-07', 'generalCount': 2809,
                'spokenCount': 721, 'overlapCount': 697, 'uniqueCount': len(records),
                'sha256': {p.name: hashlib.sha256(p.read_bytes()).hexdigest()
                           for p in sorted((DATA / 'raw').iterdir())}}
    (DATA / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8')
    print(f'Built {len(records)} words: 2809 NGSL + 721 spoken (697 overlap).')


if __name__ == '__main__':
    main()
