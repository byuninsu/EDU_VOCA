"""Build representative word POS hints from the existing Oxford mapping.

These are headword POS, not a claim about a contextual parser's result.
Additional words and expressions are app-authored annotations.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
labels = {'noun': '명사', 'verb': '동사', 'adjective': '형용사',
          'adverb': '부사', 'preposition': '전치사', 'pronoun': '대명사',
          'conjunction': '접속사', 'determiner': '한정사',
          'definite article': '정관사', 'indefinite article': '부정관사',
          'auxiliary verb': '조동사', 'modal verb': '조동사',
          'linking verb': '연결동사', 'infinitive marker': '부정사 표지',
          'number': '수사', 'ordinal number': '서수', 'exclamation': '감탄사'}
entries = json.loads((ROOT / 'data/oxford/mapping.json').read_text(encoding='utf-8'))['entries']
result = {w: list(dict.fromkeys(labels[p] for p, _ in items)) for w, items in entries.items()}
groups = {
    '명사': 'percent center behavior labor defense neighbor theater judgment chairman neighborhood voter disk manufacturer criteria gentleman supplier meter mom adviser offense dialog buyer publisher humor maker liability catalog grammar verb lover server module holder noun thirst',
    '동사': 'excite amaze wed analyze bore complicate fascinate underlie depress fulfill dedicate embarrass exhaust situate compute insure',
    '명사·동사': 'cough tape color accord favor tire honor log counsel harbor stain grin',
    '형용사': 'unclear bloody favorite tender',
    '명사·형용사': 'gray pro',
    '부사': 'virtually anymore surprisingly gently faithfully',
    '형용사·부사·감탄사': 'okay alright',
    '감탄사·동사': 'damn',
    '전치사': 'toward',
    '부사구': 'onpurpose byaccident atfirst intheend rightaway fromnowon onceinabluemoon ontheotherhand',
    '명사구': 'pieceofcake', '형용사구': 'undertheweather',
    '동사구': 'checkin pickup figureout runinto putoff workout takeforgranted checkout wakeup getup giveup findout lookfor lookafter lookforwardto turnon turnoff turnup turndown takeoff puton tryon takeout putaway cleanup comein goout comeback goback geton getoff getalongwith getover runoutof dealwith comeupwith carryon carryout setoff setup breakdown breakup calmdown cheerup slowdown hurryup holdon hangout showup fillout makesure takecareof breaktheice keepaneyeon',
}
for label, words in groups.items():
    for word in words.split():
        result[word] = label.split('·')
text = '// Generated by tools/build_word_hints.py. Oxford headword POS + app-authored additions.\n'
text += '// A word may have several parts of speech; these are not contextual tags.\n'
text += 'const wordPartsOfSpeech = <String, List<String>>{\n'
text += ''.join(f'  {json.dumps(w)}: {json.dumps(p, ensure_ascii=False)},\n' for w, p in sorted(result.items()))
text += '};\n'
(ROOT / 'lib/data/local/word_hints.dart').write_text(text, encoding='utf-8')
