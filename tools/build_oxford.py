"""Extract unambiguous CEFR facts for NGSL headwords from official HTML.

Usage: python tools/build_oxford.py oxford_source.html
Oxford data is separate from the CC BY-SA NGSL dataset. No definitions/audio.
"""
import json
import re
import sys
from html import unescape
from pathlib import Path

root = Path(__file__).resolve().parents[1]
html = Path(sys.argv[1]).read_text(encoding='utf-8')
entries = {}
for attrs, body in re.findall(r'<li\s+([^>]*data-hw[^>]*)>(.*?)</li>', html, re.S):
    fields = dict(re.findall(r'([\w-]+)="([^"]*)"', attrs))
    cefr = fields.get('data-ox5000', '').upper()
    if cefr not in ['A1', 'A2', 'B1', 'B2', 'C1']:
        continue
    word = unescape(fields['data-hw']).lower()
    pos = re.search(r'<span class="pos">(.*?)</span>', body)
    if pos:
        entries.setdefault(word, set()).add((unescape(pos[1]), cefr))
assert len(entries) > 4500, 'Incomplete official source'
words = json.loads((root / 'assets/data/ngsl.json').read_text(encoding='utf-8'))['words']
matched = {w['id']: sorted(entries[w['id']]) for w in words if w['id'] in entries}
levels = {w: next(iter({c for p, c in rows})) for w, rows in matched.items()
          if len({c for p, c in rows}) == 1}
folder = root / 'data/oxford'
folder.mkdir(exist_ok=True)
(folder / 'mapping.json').write_text(json.dumps({
    'source': 'https://www.oxfordlearnersdictionaries.com/wordlists/oxford3000-5000',
    'checked': '2026-10-08', 'policy': 'Exact headword; only unanimous CEFR across listed parts of speech. Otherwise unclassified.',
    'entries': matched, 'levels': levels}, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
lines = ['// Generated by tools/build_oxford.py. Oxford CEFR; NOT NGSL CC BY-SA.',
         'const oxfordLevels = <String, String>{']
lines += [f'  {json.dumps(w)}: "{c}",' for w, c in sorted(levels.items())]
lines += ['};', '']
(root / 'lib/data/local/oxford_levels.dart').write_text('\n'.join(lines), encoding='utf-8')
print(json.dumps({'classified': len(levels), 'ambiguous': len(matched)-len(levels),
                  'unmatched': len(words)-len(matched),
                  'bands': {c: list(levels.values()).count(c) for c in ['A1','A2','B1','B2','C1']}}))
