  /// Return only a traceable span; untranslated function words have no span.
  static String? translationFocus(WordItem word) {
    final explicit = word.translationFocus;
    if (explicit != null &&
        explicit.isNotEmpty &&
        word.translation.contains(explicit)) {
      return explicit;
    }
    final contextSpan = _contextSpans[word.id];
    if (contextSpan != null && word.translation.contains(contextSpan)) {
      return contextSpan;
    }
    for (final span in _alignments[word.id] ?? <String>[]) {
      if (word.translation.contains(span)) return span;
    }
    final gloss = word.meaning;
    if (gloss == null) return null;
    final candidates = gloss
        .replaceAll(RegExp(r'\([^)]*\)'), '')
        .split(RegExp(r'[;,/·]'))
        .map((s) => s.replaceAll('~', '').trim())
        .where((s) => s.isNotEmpty)
        .toList();
    candidates.sort((a, b) => b.length.compareTo(a.length));
    final stems = <String>[];
    for (final gloss in candidates) {
      stems.add(gloss);
      for (final ending in ['하다', '하는', '적인', '하게', '한', '다', '의']) {
        if (gloss.endsWith(ending)) {
          final stem = gloss.substring(0, gloss.length - ending.length);
          if (stem.length >= 2) stems.add(stem);
        }
      }
      if (gloss.endsWith('다')) {
        final stem = gloss.substring(0, gloss.length - 1);
        if (stem.length >= 2) {
          stems.add(stem);
          final variants = {
            '하': ['해', '했', '한', '할'],
            '되': ['돼', '됐', '된', '될'],
            '시': ['셔', '셨', '신', '실'],
            '리': ['려', '렸', '린', '릴'],
            '이': ['여', '였', '인', '일']
          };
          for (final suffix in variants.keys) {
            if (stem.endsWith(suffix)) {
              for (final replacement in variants[suffix]!) {
                stems.add(stem.substring(0, stem.length - 1) + replacement);
              }
            }
          }
        }
      }
    }
    stems.sort((a, b) => b.length.compareTo(a.length));
    for (final candidate in stems.toSet()) {
      final start = word.translation.indexOf(candidate);
      if (start >= 0 &&
          (start == 0 ||
              !RegExp(r'[가-힣]').hasMatch(word.translation[start - 1]))) {
        // Highlight the Korean surface form, including its conjugated ending.
        var end = start + candidate.length;
        while (end < word.translation.length &&
            RegExp(r'[가-힣]').hasMatch(word.translation[end])) {
          end++;
        }
        return word.translation.substring(start, end);
      }
    }
    return null;
  }
